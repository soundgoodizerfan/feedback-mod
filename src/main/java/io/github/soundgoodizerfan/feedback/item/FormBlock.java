package io.github.soundgoodizerfan.feedback.item;

import net.minecraft.network.chat.Component;
import net.minecraft.network.chat.MutableComponent;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.world.item.BlockItem;
import net.minecraft.world.item.ItemStack;
import net.minecraft.world.level.block.Block;
import net.minecraft.world.level.block.SoundType;
import net.minecraft.world.level.block.state.BlockBehaviour;
import net.minecraft.world.level.material.MapColor;

/**
 * A material as a placed block -- a storage block -- generated by {@code FormItems} like a
 * {@link FormItem}, and named by the same pattern ({@code "Block of %s"}).
 */
public class FormBlock extends Block {

    private final ResourceLocation material;
    private final String form;
    private final boolean food;

    public FormBlock(ResourceLocation material, String form) {
        this(material, form, false);
    }

    /** {@code food}: a block of foodstuff, soft and quick to break, not metal. */
    public FormBlock(ResourceLocation material, String form, boolean food) {
        super(food ? BlockBehaviour.Properties.of().mapColor(MapColor.COLOR_RED).strength(0.6f).sound(SoundType.HONEY_BLOCK) : properties(form));
        this.material = material;
        this.form = form;
        this.food = food;
    }

    /** Whether this is a block of foodstuff. */
    public boolean food() {
        return food;
    }

    /** A pipe is a thin-walled metal run; a storage block is metal; an ore (the form ends in {@code ore}) is stone, or deepslate, as hard as a vanilla ore. */
    private static BlockBehaviour.Properties properties(String form) {
        if (form.equals("loose_rock"))
            return BlockBehaviour.Properties.of().mapColor(MapColor.STONE).strength(0.5f).sound(SoundType.STONE).noOcclusion();
        if (form.equals("pipe"))
            return BlockBehaviour.Properties.of().mapColor(MapColor.METAL).strength(2f).sound(SoundType.METAL).noOcclusion();
        if (!form.endsWith("ore"))
            return BlockBehaviour.Properties.of().mapColor(MapColor.METAL).strength(5f, 6f)
                    .requiresCorrectToolForDrops().sound(SoundType.METAL);
        boolean deepslate = form.startsWith("deepslate");
        return BlockBehaviour.Properties.of().mapColor(deepslate ? MapColor.DEEPSLATE : MapColor.STONE)
                .strength(deepslate ? 4.5f : 3.0f, 3.0f).requiresCorrectToolForDrops()
                .sound(deepslate ? SoundType.DEEPSLATE : SoundType.STONE);
    }

    /** A loose rock is a small heap, not a block. */
    private static final net.minecraft.world.phys.shapes.VoxelShape LOOSE = Block.box(3, 0, 3, 13, 7, 13);

    @Override
    protected net.minecraft.world.phys.shapes.VoxelShape getShape(net.minecraft.world.level.block.state.BlockState state,
            net.minecraft.world.level.BlockGetter level, net.minecraft.core.BlockPos pos,
            net.minecraft.world.phys.shapes.CollisionContext context) {
        return form.equals("loose_rock") ? LOOSE : super.getShape(state, level, pos, context);
    }

    @Override
    public MutableComponent getName() {
        return name(material, form);
    }

    public static MutableComponent name(ResourceLocation material, String form) {
        return Component.translatable("form." + material.getNamespace() + "." + form,
                Component.translatable("material." + material.getNamespace() + "." + material.getPath()));
    }

    /** The block's item, carrying the block's pattern name rather than a lang key of its own. */
    public static class FormBlockItem extends BlockItem {

        public FormBlockItem(FormBlock block, Properties properties) {
            super(block, properties);
        }

        @Override
        public Component getName(ItemStack stack) {
            return getBlock().getName();
        }
    }
}
