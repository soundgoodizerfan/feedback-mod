package io.github.soundgoodizerfan.feedback.item;

import io.github.soundgoodizerfan.feedback.core.thermal.AmbientTable;
import io.github.soundgoodizerfan.feedback.process.Material;
import io.github.soundgoodizerfan.feedback.process.MaterialTable;
import io.github.soundgoodizerfan.feedback.registry.FormItems;
import net.minecraft.core.BlockPos;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.network.chat.Component;
import net.minecraft.world.entity.item.ItemEntity;
import net.minecraft.world.level.Level;
import net.minecraft.world.level.block.state.BlockState;
import net.minecraft.world.level.material.FlowingFluid;
import net.minecraft.world.level.material.Fluid;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.world.item.Item;
import net.minecraft.world.item.ItemStack;

/**
 * A material in one form, generated by {@code FormItems}. It has no behaviour of its own: what
 * it can become is computed from its material's hardness and the form steps naming its form.
 * Its name is a pattern ({@code "%s Plate"}) over the material's name, so a new item costs no
 * lang entry.
 */
public class FormItem extends Item {

    private final ResourceLocation material;
    private final String form;

    public FormItem(Properties properties, ResourceLocation material, String form) {
        super(properties);
        this.material = material;
        this.form = form;
    }

    public ResourceLocation material() {
        return material;
    }

    public String form() {
        return form;
    }

    /**
     * A solid piece of a material that is liquid at the room it lies in (mercury and galinstan frozen in a Cryocooler basin; gallium in a warm biome; any
     * material with a melting point under the local ambient and a {@code molten_} fluid) melts back:
     * once a second, on the ground, it spills as the fluid where it lay, a source block for a block's worth and else a flowing
     * level for each eighth of a bucket, a mere nugget going into the floor. In a pack or a chest it stays as it is.
     */
    @Override
    public boolean onEntityItemUpdate(ItemStack stack, ItemEntity entity) {
        Level level = entity.level();
        if (level.isClientSide || entity.tickCount % 20 != 0 || !entity.onGround())
            return false;
        Material m = MaterialTable.get().materials().get(material);
        if (m == null || m.thermal().meltingPoint().filter(mp -> mp.value() < AmbientTable.at(level).value()).isEmpty())
            return false;
        Fluid source = BuiltInRegistries.FLUID.get(ResourceLocation.fromNamespaceAndPath(material.getNamespace(), "molten_" + material.getPath()));
        if (!(source instanceof FlowingFluid flowing))
            return false;
        int mb = FormItems.volume(form) * stack.getCount();
        BlockPos at = entity.blockPosition();
        BlockState here = level.getBlockState(at);
        if (here.isAir() || here.canBeReplaced(source)) {
            if (mb >= 1000)
                level.setBlockAndUpdate(at, flowing.getSource().defaultFluidState().createLegacyBlock());
            else if (mb >= 63)
                level.setBlockAndUpdate(at, flowing.getFlowing(Math.max(1, Math.min(7, Math.round(mb / 125f))), false).createLegacyBlock());
        } else {
            return false;
        }
        entity.discard();
        return true;
    }

    @Override
    public Component getName(ItemStack stack) {
        return FormBlock.name(material, form);
    }
}
