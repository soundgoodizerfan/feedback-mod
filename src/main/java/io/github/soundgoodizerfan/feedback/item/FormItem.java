package io.github.soundgoodizerfan.feedback.item;

import net.minecraft.network.chat.Component;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.world.item.Item;
import net.minecraft.world.item.ItemStack;

/**
 * A material in one form, generated by {@code FormItems}. It has no behaviour of its own: what
 * it can become is computed from its material's hardness and the form steps naming its form.
 * Its name is a pattern ({@code "%s Plate"}) over the material's name, so a new item costs no
 * lang entry.
 */
public class FormItem extends Item {

    private final ResourceLocation material;
    private final String form;

    public FormItem(Properties properties, ResourceLocation material, String form) {
        super(properties);
        this.material = material;
        this.form = form;
    }

    public ResourceLocation material() {
        return material;
    }

    public String form() {
        return form;
    }

    @Override
    public Component getName(ItemStack stack) {
        return FormBlock.name(material, form);
    }
}
