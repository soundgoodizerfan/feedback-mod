package io.github.soundgoodizerfan.feedback.vehicle.engine;

import com.mojang.serialization.MapCodec;
import net.minecraft.core.BlockPos;
import net.minecraft.world.Containers;
import net.minecraft.world.InteractionResult;
import net.minecraft.world.entity.player.Player;
import net.minecraft.world.level.Level;
import net.minecraft.world.level.block.BaseEntityBlock;
import net.minecraft.world.level.block.RenderShape;
import net.minecraft.world.level.block.entity.BlockEntity;
import net.minecraft.world.level.block.state.BlockState;
import net.minecraft.world.phys.BlockHitResult;
import org.jetbrains.annotations.Nullable;

/** Where engines are designed ({@code docs/feedback_vehicles_spec.md} section 6): use it to open the editor. */
public class EngineStandBlock extends BaseEntityBlock {

    public static final MapCodec<EngineStandBlock> CODEC = simpleCodec(EngineStandBlock::new);

    public EngineStandBlock(Properties properties) {
        super(properties);
    }

    @Override
    protected MapCodec<? extends BaseEntityBlock> codec() {
        return CODEC;
    }

    @Override
    protected RenderShape getRenderShape(BlockState state) {
        return RenderShape.MODEL;
    }

    @Override
    protected InteractionResult useWithoutItem(BlockState state, Level level, BlockPos pos, Player player, BlockHitResult hit) {
        if (!(level.getBlockEntity(pos) instanceof EngineStandBlockEntity stand))
            return InteractionResult.PASS;
        if (!level.isClientSide)
            player.openMenu(stand, buf -> {
                buf.writeBlockPos(pos);
                EngineDesign.STREAM_CODEC.encode(buf, stand.design());
                io.github.soundgoodizerfan.feedback.vehicle.transmission.TransmissionDesign.STREAM_CODEC.encode(buf, stand.transmission());
                buf.writeBoolean(stand.transmissionMode());
            });
        return InteractionResult.sidedSuccess(level.isClientSide);
    }

    @Override
    protected void onRemove(BlockState state, Level level, BlockPos pos, BlockState newState, boolean movedByPiston) {
        if (!state.is(newState.getBlock()) && level.getBlockEntity(pos) instanceof EngineStandBlockEntity stand)
            Containers.dropContents(level, pos, stand);
        super.onRemove(state, level, pos, newState, movedByPiston);
    }

    @Nullable
    @Override
    public BlockEntity newBlockEntity(BlockPos pos, BlockState state) {
        return new EngineStandBlockEntity(pos, state);
    }
}
